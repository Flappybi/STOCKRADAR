export function calculateRadarScore(
  metrics: StockData["metrics"],
  weights: StrategyWeights = DEFAULT_STRATEGY_WEIGHTS
): number {
  const totalWeight =
    weights.quality +
    weights.growth +
    weights.momentum +
    weights.value +
    weights.risk;

  if (totalWeight <= 0) return 0;

  const rawScore =
    (metrics.quality * weights.quality +
      metrics.growth * weights.growth +
      metrics.momentum * weights.momentum +
      metrics.value * weights.value +
      metrics.risk * weights.risk) /
    totalWeight;

  return Number(rawScore.toFixed(1));
}
